//! Shell integration scripts.
//!
//! The scripts are constants: `prompty init` prints one, the shell evaluates
//! it, and from then on every prompt is a single fork of a single binary. The
//! binary name is interpolated from the one source of truth, so renaming the
//! application cannot leave a stale script behind.
//!
//! Each script is assembled from pieces rather than written twice: the parts
//! that differ between the two variants are the ones named after what they do.

const std = @import("std");

const canvas = @import("../domain/canvas.zig");
const metadata = @import("metadata.zig");

/// The integration for one shell. `duration` bakes the option into the
/// generated script, which for zsh means writing `RPROMPT`: that is what keeps
/// the number at the right edge and the cursor after the chevron while the line
/// is edited. bash has no right prompt, so there the duration stays next to the
/// prompt, in the dimmed placement.
pub fn script(shell: canvas.Shell, duration: bool) []const u8 {
    return switch (shell) {
        .zsh => if (duration) zsh_script_with_duration else zsh_script,
        .bash => if (duration) bash_script_with_duration else bash_script,
        .plain => "",
    };
}

comptime {
    if (metadata.name.len == 0) @compileError("the application name must come from build.zig.zon");
}

const zsh_head =
    "# prompty shell integration for zsh. Generated by `prompty init zsh`.\n" ++
    "if [[ -o interactive && -z $PROMPTY_LOADED ]]; then\n" ++
    "  typeset -g PROMPTY_LOADED=1\n" ++
    "  # prompty renders the whole prompt itself: the expansions below would\n" ++
    "  # only let a directory or branch name run code.\n" ++
    "  unsetopt prompt_subst prompt_bang 2>/dev/null\n" ++
    "  autoload -Uz add-zsh-hook\n" ++
    "  zmodload zsh/datetime 2>/dev/null\n" ++
    "  command " ++ metadata.name ++ " theme detect >/dev/null 2>&1\n" ++
    "  typeset -g _prompty_started_at=\n" ++
    "  _prompty_preexec() { _prompty_started_at=${EPOCHREALTIME:-} }\n" ++
    "  _prompty_precmd() {\n" ++
    "    local exit_code=$?\n" ++
    "    local started_at=${_prompty_started_at:-}\n" ++
    "    local duration_ms=0\n" ++
    "    _prompty_started_at=\n" ++
    "    if [[ -n $started_at && -n ${EPOCHREALTIME:-} ]]; then\n" ++
    "      duration_ms=$(( (EPOCHREALTIME - started_at) * 1000 ))\n" ++
    "      # zsh does that arithmetic in floating point (150.00009536743164,\n" ++
    "      # or 1500. when it lands exactly): the prompt wants whole ms.\n" ++
    "      duration_ms=${duration_ms%.*}\n" ++
    "    fi\n" ++
    "    local rendered\n" ++
    "    rendered=\"$(PROMTY_LAST_EXIT=$exit_code PROMTY_LAST_DURATION_MS=$duration_ms ";

/// The same for every zsh variant: install both hooks, once.
const zsh_tail =
    "  }\n" ++
    "  add-zsh-hook preexec _prompty_preexec\n" ++
    "  add-zsh-hook precmd _prompty_precmd\n" ++
    "fi\n";

pub const zsh_script = zsh_head ++ metadata.name ++
    " render --shell=zsh)\"\n" ++
    "    PROMPT=${rendered:-%# }\n" ++
    zsh_tail;

/// The same script, with the duration in `RPROMPT`.
///
/// The binary prints the line, a separator, and the segment for the right edge;
/// splitting them here is what gives the prompt its two halves. `RPROMPT` is
/// zsh's own right-hand prompt: it is drawn at the edge, redrawn as the line is
/// edited, and hidden when the line grows into it — none of which a padded
/// string can do.
const zsh_script_with_duration = zsh_head ++ metadata.name ++
    " render --shell=zsh --duration)\"\n" ++
    "    PROMPT=${rendered%%$'\\x1f'*}\n" ++
    "    RPROMPT=${rendered#*$'\\x1f'}\n" ++
    "    [[ -n $PROMPT ]] || PROMPT='%# '\n" ++
    zsh_tail;

const bash_head =
    "# prompty shell integration for bash. Generated by `prompty init bash`.\n" ++
    "if [[ $- == *i* && -z $PROMPTY_LOADED ]]; then\n" ++
    "  PROMPTY_LOADED=1\n" ++
    "  command " ++ metadata.name ++ " theme detect >/dev/null 2>&1\n" ++
    "  # A prompt string is expanded a second time when `promptvars` is on, so\n" ++
    "  # a directory called `$(...)` would run on every prompt. prompty renders\n" ++
    "  # the whole prompt itself and needs no expansion.\n" ++
    "  shopt -u promptvars\n";

/// The timing, which bash can only get from a `DEBUG` trap: it runs before each
/// command, and records only the first one, which is when the line started.
/// Parameter expansion only, so it forks nothing per command. A handler the
/// user already had is kept and run after ours, not replaced.
const bash_timing =
    "  # bash has no preexec hook: the DEBUG trap runs before each command and\n" ++
    "  # records only the first one. A handler you already had is kept and run.\n" ++
    "  _prompty_started_at=\n" ++
    "  _prompty_user_debug=$(trap -p DEBUG)\n" ++
    "  # \"trap -- 'BODY' DEBUG\" -> BODY. The quotes in the pattern are\n" ++
    "  # escaped so that it stays a pattern and not a quoted string.\n" ++
    "  _prompty_user_debug=${_prompty_user_debug#*\\\'}\n" ++
    "  _prompty_user_debug=${_prompty_user_debug%\\\'*}\n" ++
    "  trap '[[ -n $_prompty_started_at ]] || _prompty_started_at=${EPOCHREALTIME//[.,]/}; [[ -z $_prompty_user_debug ]] || eval \"$_prompty_user_debug\"' DEBUG\n";

const bash_precmd_head =
    "  _prompty_precmd() {\n" ++
    "    local exit_code=$?\n";

/// Whole milliseconds, from a locale-formatted `EPOCHREALTIME`: a Spanish shell
/// gives 1793542627,390303 and a C one 1793542627.390303, so the separator is
/// dropped before the subtraction and the result is microseconds.
const bash_timing_body =
    "    local started=${_prompty_started_at:-}\n" ++
    "    _prompty_started_at=\n" ++
    "    local duration_ms=0\n" ++
    "    if [[ -n $started && -n ${EPOCHREALTIME:-} ]]; then\n" ++
    "      local now=${EPOCHREALTIME//[.,]/}\n" ++
    "      duration_ms=$(( (now - started) / 1000 ))\n" ++
    "    fi\n";

/// The same for every bash variant: add the hook to `PROMPT_COMMAND`, which is
/// a string in older bash and an array in 5.1+.
const bash_tail =
    " render --shell=bash)\"\n" ++
    "    PS1=${rendered:-\\$ }\n" ++
    "  }\n" ++
    "  # PROMPT_COMMAND is a string in older bash and an array in bash 5.1+,\n" ++
    "  # so the hook is added to whichever it is -- and never twice.\n" ++
    "  case \"$(declare -p PROMPT_COMMAND 2>/dev/null)\" in\n" ++
    "    \"declare -a\"*)\n" ++
    "      [[ \" ${PROMPT_COMMAND[*]} \" == *\" _prompty_precmd \"* ]] ||\n" ++
    "        PROMPT_COMMAND=(_prompty_precmd \"${PROMPT_COMMAND[@]}\")\n" ++
    "      ;;\n" ++
    "    *)\n" ++
    "      case ${PROMPT_COMMAND-} in\n" ++
    "        *_prompty_precmd*) ;;\n" ++
    "        \"\") PROMPT_COMMAND=\"_prompty_precmd\" ;;\n" ++
    "        *) PROMPT_COMMAND=\"_prompty_precmd;$PROMPT_COMMAND\" ;;\n" ++
    "      esac\n" ++
    "      ;;\n" ++
    "  esac\n" ++
    "fi\n";

pub const bash_script = bash_head ++ bash_precmd_head ++
    "    local rendered\n" ++
    "    rendered=\"$(PROMTY_LAST_EXIT=$exit_code " ++ metadata.name ++ bash_tail;

/// bash has no right prompt, and lying about the width in `PS1` would break
/// readline's redraw. The timing is wired up, and the number stays where bash
/// can put it: after the prompt, dimmed.
const bash_script_with_duration = bash_head ++ bash_timing ++ bash_precmd_head ++ bash_timing_body ++
    "    local rendered\n" ++
    "    rendered=\"$(PROMTY_LAST_EXIT=$exit_code PROMTY_LAST_DURATION_MS=$duration_ms " ++
    metadata.name ++ bash_tail;

test "every interactive shell gets a loadable script" {
    try std.testing.expect(std.mem.startsWith(u8, zsh_script, "# prompty shell integration for zsh"));
    try std.testing.expect(std.mem.indexOf(u8, zsh_script, "add-zsh-hook precmd _prompty_precmd") != null);
    try std.testing.expect(std.mem.indexOf(u8, zsh_script, "PROMPT=${rendered:-%# }") != null);
    try std.testing.expect(std.mem.indexOf(u8, zsh_script, metadata.name ++ " render --shell=zsh") != null);
    try std.testing.expect(std.mem.indexOf(u8, zsh_script, metadata.name ++ " theme detect") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash_script, metadata.name ++ " theme detect") != null);

    try std.testing.expect(std.mem.startsWith(u8, bash_script, "# prompty shell integration for bash"));
    try std.testing.expect(std.mem.indexOf(u8, bash_script, "PROMPT_COMMAND=\"_prompty_precmd\"") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash_script, metadata.name ++ " render --shell=bash") != null);
}

test "the scripts are idempotent" {
    try std.testing.expect(std.mem.indexOf(u8, zsh_script, "-z $PROMPTY_LOADED") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash_script, "-z $PROMPTY_LOADED") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash_script, "*_prompty_precmd*") != null);
}

test "the bash hook survives a PROMPT_COMMAND array" {
    try std.testing.expect(std.mem.indexOf(u8, bash_script, "declare -a") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash_script, "PROMPT_COMMAND=(_prompty_precmd") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash_script, "PROMPT_COMMAND=\"_prompty_precmd\"") != null);
}

test "neither shell is left able to expand the prompt" {
    try std.testing.expect(std.mem.indexOf(u8, bash_script, "shopt -u promptvars") != null);
    try std.testing.expect(std.mem.indexOf(u8, zsh_script, "unsetopt prompt_subst") != null);
}

test "the prompt survives a failing render" {
    try std.testing.expect(std.mem.indexOf(u8, zsh_script, "PROMPT=${rendered:-%# }") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash_script, "PS1=${rendered:-\\$ }") != null);
}

test "plain has no integration because it needs no escaping" {
    try std.testing.expectEqualStrings("", script(.plain, false));
    try std.testing.expectEqualStrings(zsh_script, script(.zsh, false));
    try std.testing.expectEqualStrings(bash_script, script(.bash, false));
}

test "the duration option bakes RPROMPT into the zsh script" {
    const zsh = script(.zsh, true);
    try std.testing.expect(std.mem.indexOf(u8, zsh, "render --shell=zsh --duration") != null);
    try std.testing.expect(std.mem.indexOf(u8, zsh, "PROMPT=${rendered%%$'\\x1f'*}") != null);
    try std.testing.expect(std.mem.indexOf(u8, zsh, "RPROMPT=${rendered#*$'\\x1f'}") != null);
    try std.testing.expect(std.mem.indexOf(u8, zsh, "COLUMNS") == null);
    try std.testing.expect(std.mem.indexOf(u8, zsh, "add-zsh-hook precmd _prompty_precmd") != null);
    try std.testing.expect(std.mem.indexOf(u8, zsh, "[[ -n $PROMPT ]] || PROMPT='%# '") != null);

    try std.testing.expect(std.mem.indexOf(u8, script(.zsh, false), "--duration") == null);
    try std.testing.expect(std.mem.indexOf(u8, script(.zsh, false), "RPROMPT") == null);
}

test "the bash script times the command but keeps the number on the line" {
    const bash = script(.bash, true);
    try std.testing.expect(std.mem.indexOf(u8, bash, "trap ") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash, "PROMTY_LAST_DURATION_MS=$duration_ms") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash, "--duration") == null);
    try std.testing.expect(std.mem.indexOf(u8, script(.bash, false), "DEBUG") == null);
}

test "the duration is whole milliseconds in both shells" {
    try std.testing.expect(std.mem.indexOf(u8, zsh_script, "duration_ms=${duration_ms%.*}") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash_script_with_duration, "${EPOCHREALTIME//[.,]/}") != null);
    try std.testing.expect(std.mem.indexOf(u8, bash_script_with_duration, "duration_ms=$(( (now - started) / 1000 ))") != null);
}

test "the render command is on one line so the shell sees one command" {
    inline for (.{ zsh_script, bash_script, zsh_script_with_duration, bash_script_with_duration }) |text| {
        const line_start = std.mem.lastIndexOfScalar(u8, text[0..std.mem.indexOf(u8, text, " render --shell=").?], '\n').?;
        try std.testing.expect(std.mem.indexOfScalar(u8, text[line_start..], '\n') != null);
        try std.testing.expect(std.mem.indexOf(u8, text, "command\n") == null);
    }
}
